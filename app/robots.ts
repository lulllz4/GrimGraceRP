import type { MetadataRoute } from 'next'

/**
 * Поисковиков на сайт не пускаем.
 *
 * Сайт открыт по ссылке — так и задумано, — но в выдачу попадать не должен:
 * это закрытое сообщество, и посты с анкетами написаны для своих, а не для
 * случайного прохожего из поиска.
 *
 * Один этот файл — только просьба не заходить. Поэтому вторым слоем в
 * layout.tsx стоит запрет на индексацию в самой странице: он сработает
 * даже там, где robots.txt прочитать не успели.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: [{ userAgent: '*', disallow: '/' }],
  }
}
